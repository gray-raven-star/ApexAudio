import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';

globalThis.ResizeObserver = class { observe() {} };
globalThis.document = {documentElement:{dataset:{theme:'dark'}}};
globalThis.devicePixelRatio = 1;
const source = await readFile(new URL('../ui/timeline.js', import.meta.url), 'utf8');
const {Timeline} = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const strokes=[];
const ctx={scale(){},clearRect(){},beginPath(){},moveTo(x,y){this.x=x;this.y=y;},lineTo(x,y){this.endX=x;},fillText(){},fillRect(){},stroke(){strokes.push({color:this.strokeStyle,y:this.y,x:this.x,endX:this.endX});}};
const canvas={clientWidth:800,clientHeight:280,getContext(){return ctx;},addEventListener(){}};
const timeline=new Timeline(canvas,()=>{});
const take={id:'final-output',duration:1,haptics:{blocks:[{seconds:.2,span:.01,left:.4,right:.5,trigger:.6,supplementLeft:null,supplementRight:null,supplementTrigger:null}]}};
timeline.set(take,{peaks:[]});
assert(strokes.some(s=>s.color==='#d58cf8'&&Math.abs(s.y-(127-.4*19))<.001), 'final left output should be drawn');
assert(strokes.some(s=>s.color==='#9c91ff'&&Math.abs(s.y-(185-.5*19))<.001), 'final right output should be drawn');
assert(strokes.some(s=>s.color==='#e7a8cf'&&Math.abs(s.y-(241-.6*19))<.001), 'final trigger output should be drawn');
strokes.length=0;
timeline.set({...take,id:'supplement',haptics:{blocks:[{...take.haptics.blocks[0],supplementLeft:.1,supplementRight:.2,supplementTrigger:.3}]}},{peaks:[]});
assert(strokes.some(s=>s.color==='#d58cf8'&&Math.abs(s.y-(127-.1*19))<.001), 'separate supplement should take priority when available');
console.log('PASS: final output fallback and separate supplement rendering');
strokes.length=0;timeline.gain=4;
const quietTake={id:'quiet',duration:1,haptics:{blocks:[{seconds:.2,span:.04,supplementLeft:.03,supplementRight:null,supplementTrigger:0}]}};
const original=structuredClone(quietTake);
timeline.set(quietTake,{peaks:[]});
assert(strokes.some(s=>s.color==='#d58cf8'&&Math.abs(s.y-(127-.03*4*19))<.001),'display gain makes quiet vibrations visible');
assert(!strokes.some(s=>s.color==='#9c91ff'||s.color==='#e7a8cf'),'missing or zero amplitude never becomes a positive vibration');
assert.deepEqual(quietTake,original,'display gain leaves recorded amplitudes unchanged');
console.log('PASS: curve magnification preserves measurements and missing data');
timeline.gain=1;timeline.hapticSource='both';strokes.length=0;
const polled={...take,id:'polled',haptics:{samplingMethod:'instantaneous-poll',blocks:[{seconds:.2,span:0,left:.4,supplementLeft:.1}]}};
timeline.set(polled,{peaks:[]});
assert(strokes.some(s=>s.color==='#a4b1c5'&&Math.abs(s.y-(127-.4*19))<.001),'both mode exposes mixed output separately');
assert(strokes.some(s=>s.color==='#d58cf8'&&Math.abs(s.y-(127-.1*19))<.001),'both mode retains supplement');
assert(strokes.filter(s=>['#a4b1c5','#d58cf8'].includes(s.color)).every(s=>Math.abs(s.endX-s.x)<=2.001),'instantaneous readings are points, never sustained spans');
strokes.length=0;
timeline.set({...polled,id:'old-poll',haptics:{note:'正式 Engine 诊断峰值，旧录音',blocks:[{seconds:.2,span:.09,left:.4,supplementLeft:.1}]}},{peaks:[]});
assert(strokes.some(s=>s.color==='#d58cf8'&&Math.abs(s.x-(49+.29*732))<.001&&Math.abs(s.endX-s.x)<=2.001),'old diagnostic readings move to their original receipt time and remain points');
console.log('PASS: separate output sources and honest instantaneous timing');
